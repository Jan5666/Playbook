function logoFor(ticker, market) {
  if (!ticker || !market) return null;
  const entry = LOGO_MANIFEST[market + ':' + ticker];
  if (!entry) return null;
  // `1` means "art is at the default path for this key" — expanded here so every
  // caller keeps seeing the same { f } shape it always did.
  if (entry === 1) return { f: market + '-' + ticker + '.png' };
  return entry;
}

